import time
import mcp_http01 as http01
from mcp_certificate_names import short_names_allowed

ALPN = b'acme-tls/1'
MAX_HELLO = 65536
MAX_WIRE = 262144
DEADLINE = 5
MAX_AGE = 900
FIELDS = ('alpn_ready', 'alpn_source_networks', 'alpn_public_access')
NAME = re.compile(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)*')


def normalize_fields(cfg):
    if type(cfg['alpn_ready']) is not bool:
        raise ValueError('TLS-ALPN authorization must be true or false.')
    proxy = dict(http_mode='standalone', http_ready=cfg['alpn_ready'],
                 http_source_networks=cfg['alpn_source_networks'], http_public_access=cfg['alpn_public_access'])
    http01.normalize_fields(proxy, proxy)
    cfg['alpn_source_networks'] = proxy['http_source_networks']
    return cfg


def prerequisites(cfg):
    issues = []
    if not cfg['alpn_ready']:
        issues.append('Authorize temporary port-443 access and confirm the CA can reach this appliance for every requested hostname.')
    if not cfg['alpn_public_access'] and not cfg['alpn_source_networks']:
        issues.append('Specify the CA validation sources or explicitly allow public TLS-ALPN validation.')
    if not ssl.HAS_ALPN:
        issues.append('The appliance TLS library does not support ALPN.')
    if not shutil.which('nft'):
        issues.append('The nftables client is required for the TLS-ALPN responder.')
    return issues


class Reader:
    def __init__(self, data):
        self.data, self.pos = data, 0

    def take(self, count):
        if count < 0 or self.pos + count > len(self.data):
            raise ValueError('Truncated structure.')
        result = self.data[self.pos:self.pos + count]
        self.pos += count
        return result

    def number(self, count):
        return int.from_bytes(self.take(count), 'big')

    def vector(self, width):
        return self.take(self.number(width))

    def end(self):
        if self.pos != len(self.data):
            raise ValueError('Unexpected trailing data.')


def client_name(body):
    """Validate routing fields only; OpenSSL validates the complete TLS exchange."""
    reader = Reader(body)
    if reader.number(2) < 0x0303:
        raise ValueError('TLS 1.2 or newer is required.')
    reader.take(32)
    if len(reader.vector(1)) > 32:
        raise ValueError('Invalid session ID.')
    ciphers = reader.vector(2)
    if not ciphers or len(ciphers) % 2:
        raise ValueError('Invalid cipher list.')
    if reader.vector(1) != b'\0':
        raise ValueError('TLS compression is not supported.')
    extensions = Reader(reader.vector(2))
    reader.end()
    found = {}
    while extensions.pos < len(extensions.data):
        kind, value = extensions.number(2), extensions.vector(2)
        if kind in found:
            raise ValueError('Duplicate TLS extension.')
        found[kind] = value
    if 0 not in found or 16 not in found:
        raise ValueError('SNI and ALPN are required.')
    names = Reader(found[0])
    entries = Reader(names.vector(2))
    names.end()
    if entries.number(1) != 0:
        raise ValueError('A DNS SNI hostname is required.')
    name = entries.vector(2).decode('ascii').lower()
    entries.end()
    if len(name) > 253 or not NAME.fullmatch(name):
        raise ValueError('Invalid SNI hostname.')
    protocol = Reader(found[16])
    names = Reader(protocol.vector(2))
    protocol.end()
    if names.vector(1) != ALPN:
        raise ValueError('Only acme-tls/1 is supported.')
    names.end()
    return name


def receive_exact(sock, count, deadline):
    chunks = bytearray()
    while len(chunks) < count:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise TimeoutError('TLS handshake timed out.')
        sock.settimeout(remaining)
        value = sock.recv(count - len(chunks))
        if not value:
            raise ValueError('Incomplete TLS handshake.')
        chunks.extend(value)
    return bytes(chunks)


def receive_hello(sock, deadline):
    raw, handshake = bytearray(), bytearray()
    for _ in range(64):
        header = receive_exact(sock, 5, deadline)
        size = int.from_bytes(header[3:5], 'big')
        if header[0] != 22 or header[1] != 3 or not 0 < size <= 16384:
            raise ValueError('Expected a TLS handshake record.')
        data = receive_exact(sock, size, deadline)
        raw.extend(header + data)
        handshake.extend(data)
        if len(raw) > MAX_HELLO + 320:
            raise ValueError('Oversized ClientHello.')
        if len(handshake) < 4:
            continue
        length = int.from_bytes(handshake[1:4], 'big')
        if handshake[0] != 1 or not 38 <= length <= MAX_HELLO - 4:
            raise ValueError('Invalid ClientHello.')
        if len(handshake) >= length + 4:
            if len(handshake) != length + 4:
                raise ValueError('Unexpected data after ClientHello.')
            return client_name(bytes(handshake[4:])), bytes(raw)
    raise ValueError('Too many fragmented TLS records.')


def der_items(data):
    """Bounded DER traversal, only for checking generated X.509 extensions."""
    reader = Reader(data)
    items = []
    while reader.pos < len(data):
        tag, size = reader.number(1), reader.number(1)
        if size & 0x80:
            count = size & 0x7f
            if not 1 <= count <= 3:
                raise ValueError('Invalid DER length.')
            raw = reader.take(count)
            size = int.from_bytes(raw, 'big')
            if raw[0] == 0 or size < 128:
                raise ValueError('Noncanonical DER length.')
        items.append((tag, reader.take(size)))
    return items


def sequence(data):
    items = der_items(data)
    if len(items) != 1 or items[0][0] != 0x30:
        raise ValueError('Expected DER sequence.')
    return der_items(items[0][1])


def verify_certificate(pem, name, digest):
    if pem.count('-----BEGIN CERTIFICATE-----') != 1 or len(pem) > 65536:
        raise ValueError('A single challenge certificate is required.')
    fields = sequence(ssl.PEM_cert_to_DER_cert(pem))
    if len(fields) != 3 or fields[0][0] != 0x30:
        raise ValueError('Invalid challenge certificate.')
    extensions = [value for tag, value in der_items(fields[0][1]) if tag == 0xa3]
    if len(extensions) != 1:
        raise ValueError('Missing challenge extensions.')
    values = {}
    for tag, value in sequence(extensions[0]):
        if tag != 0x30:
            raise ValueError('Invalid extension sequence.')
        parts = der_items(value)
        if len(parts) not in (2, 3) or parts[0][0] != 6 or parts[-1][0] != 4:
            raise ValueError('Invalid certificate extension.')
        critical = False
        if len(parts) == 3:
            if parts[1] != (1, bytes([255])):
                raise ValueError('Invalid critical extension flag.')
            critical = True
        oid = parts[0][1]
        if oid in values:
            raise ValueError('Duplicate certificate extension.')
        values[oid] = (critical, parts[-1][1])
    san = values.get(bytes.fromhex('551d11'))
    identifier = values.get(bytes.fromhex('2b0601050507011f'))
    if not san or sequence(san[1]) != [(0x82, name.encode('ascii'))]:
        raise ValueError('Challenge certificate must contain exactly the requested DNS name.')
    if identifier != (True, bytes([4, 32]) + digest):
        raise ValueError('Challenge acmeIdentifier is missing, noncritical, or incorrect.')


def private_read(path, limit=65536):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, 'rb') as stream:
        st = os.fstat(stream.fileno())
        if not stat.S_ISREG(st.st_mode) or st.st_uid != os.geteuid() or st.st_mode & 0o022 or st.st_nlink != 1 or st.st_size > limit:
            raise ValueError('Unsafe challenge file.')
        return stream.read(limit + 1)


def atomic(path, value):
    fd, temporary = tempfile.mkstemp(prefix='.alpn-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            os.fchmod(stream.fileno(), 0o600)
            stream.write(value)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def tls_context(bundle):
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.minimum_version = ssl.TLSVersion.TLSv1_2
    context.set_alpn_protocols([ALPN.decode()])
    context.options |= ssl.OP_NO_TICKET
    context.num_tickets = 0
    context.load_cert_chain(str(bundle))
    return context


def publish(stage, cfg, event, name, token, digest_text):
    if name not in {cfg['primary_domain'], *cfg['alternative_names']} or not NAME.fullmatch(name) or not http01.TOKEN.fullmatch(token):
        raise ValueError('TLS challenge does not belong to the saved certificate order.')
    if '.' not in name and not short_names_allowed(cfg):
        raise ValueError('Short TLS challenge names require an internal CA.')
    if not re.fullmatch(r'(?:[a-fA-F0-9]{64}|(?:[a-fA-F0-9]{2}:){31}[a-fA-F0-9]{2})', digest_text):
        raise ValueError('Invalid TLS challenge digest.')
    digest = bytes.fromhex(digest_text.replace(':', ''))
    root = Path(stage) / 'tls-challenges'
    if root.is_symlink() or not root.is_dir():
        raise ValueError('The TLS-ALPN responder is not active.')
    index = root / (hashlib.sha256(name.encode()).hexdigest() + '.json')
    slot = hashlib.sha256((name + chr(0) + token).encode()).hexdigest()
    if event == 'clean_challenge':
        if index.exists() and json.loads(private_read(index))['slot'] == slot:
            index.unlink()
        (root / (slot + '.pem')).unlink(missing_ok=True)
        return
    if event != 'deploy_challenge':
        raise ValueError('Unexpected TLS challenge event.')
    source = Path(stage) / 'alpn-generated'
    if source.is_symlink():
        raise ValueError('Unsafe generated certificate directory.')
    cert = private_read(source / (name + '.crt.pem'))
    key = private_read(source / (name + '.key.pem'))
    verify_certificate(cert.decode('ascii'), name, digest)
    bundle = root / (slot + '.pem')
    data = cert + bytes([10]) + key
    atomic(bundle, data)
    try:
        tls_context(bundle)
        result = subprocess.run(['/usr/bin/openssl', 'x509', '-in', str(bundle), '-noout', '-startdate', '-enddate'], capture_output=True, text=True, timeout=5)
        dates = dict(line.split('=', 1) for line in result.stdout.splitlines() if '=' in line)
        start, end = ssl.cert_time_to_seconds(dates['notBefore']), ssl.cert_time_to_seconds(dates['notAfter'])
        if result.returncode or not start <= time.time() < end:
            raise ValueError('Challenge certificate is outside its validity period.')
        atomic(index, json.dumps({'name': name, 'slot': slot, 'sha256': hashlib.sha256(data).hexdigest(),
                                  'expires': min(end, time.time() + MAX_AGE)}).encode())
    except BaseException:
        bundle.unlink(missing_ok=True)
        raise


class Handler(socketserver.BaseRequestHandler):
    def handle(self):
        sock = self.request
        deadline = time.monotonic() + DEADLINE
        try:
            name, raw = receive_hello(sock, deadline)
            context = self.server.context(name)
            incoming, outgoing = ssl.MemoryBIO(), ssl.MemoryBIO()
            tls = context.wrap_bio(incoming, outgoing, server_side=True)
            incoming.write(raw)
            wire = len(raw)
            def flush():
                while outgoing.pending:
                    remaining = deadline - time.monotonic()
                    if remaining <= 0:
                        raise TimeoutError('TLS handshake timed out.')
                    sock.settimeout(remaining)
                    sock.sendall(outgoing.read())
            for _ in range(128):
                try:
                    tls.do_handshake()
                    flush()
                    if tls.selected_alpn_protocol() != ALPN.decode():
                        return
                    try:
                        tls.unwrap()
                    except (ssl.SSLWantReadError, ssl.SSLWantWriteError):
                        pass
                    flush()
                    return
                except ssl.SSLWantReadError:
                    flush()
                    remaining = deadline - time.monotonic()
                    if remaining <= 0:
                        return
                    sock.settimeout(remaining)
                    chunk = sock.recv(16384)
                    if not chunk:
                        return
                    wire += len(chunk)
                    if wire > MAX_WIRE:
                        return
                    incoming.write(chunk)
                except ssl.SSLWantWriteError:
                    flush()
        except (OSError, ValueError, TypeError, KeyError):
            return


class Server(socketserver.ThreadingTCPServer):
    daemon_threads = True
    allow_reuse_address = True
    request_queue_size = 16

    def __init__(self, address, family, root, names):
        self.address_family = family
        self.root, self.names = Path(root), frozenset(names)
        self.slots = threading.BoundedSemaphore(16)
        self.connections, self.connection_lock = set(), threading.Lock()
        try:
            super().__init__(address, Handler, bind_and_activate=False)
            if family == socket.AF_INET6:
                self.socket.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 1)
            self.server_bind()
            self.server_activate()
        except BaseException:
            self.server_close()
            raise

    def context(self, name):
        if name not in self.names:
            raise ValueError('Unrequested SNI hostname.')
        row = json.loads(private_read(self.root / (hashlib.sha256(name.encode()).hexdigest() + '.json'), 2048))
        if row['name'] != name or not re.fullmatch(r'[0-9a-f]{64}', row['slot']) or not time.time() < row['expires'] <= time.time() + MAX_AGE + 5:
            raise ValueError('Inactive TLS challenge.')
        bundle = self.root / (row['slot'] + '.pem')
        if hashlib.sha256(private_read(bundle)).hexdigest() != row['sha256']:
            raise ValueError('Modified TLS challenge identity.')
        return tls_context(bundle)

    def process_request(self, request, client_address):
        if not self.slots.acquire(blocking=False):
            self.shutdown_request(request)
            return
        with self.connection_lock:
            self.connections.add(request)
        try:
            super().process_request(request, client_address)
        except BaseException:
            with self.connection_lock:
                self.connections.discard(request)
            self.slots.release()
            raise

    def process_request_thread(self, request, client_address):
        try:
            super().process_request_thread(request, client_address)
        finally:
            with self.connection_lock:
                self.connections.discard(request)
            self.slots.release()

    def close_connections(self):
        with self.connection_lock:
            for request in tuple(self.connections):
                try:
                    request.shutdown(socket.SHUT_RDWR)
                except OSError:
                    pass
                request.close()

    def handle_error(self, request, client_address):
        pass


class Responder(AbstractContextManager):
    def __init__(self, cfg, stage):
        self.cfg, self.stage = cfg, Path(stage)
        self.root = self.stage / 'tls-challenges'
        self.generated = self.stage / 'alpn-generated'
        self.servers, self.threads = [], []
        self.old_sigterm = None
        self.firewall = http01.Firewall({'http_public_access': cfg['alpn_public_access'],
                                        'http_source_networks': cfg['alpn_source_networks']}, port=443, prefix='mcp-alpn01')

    def __enter__(self):
        issues = prerequisites(self.cfg)
        if issues:
            raise ValueError(' '.join(issues))
        for directory in (self.root, self.generated):
            if directory.exists() or directory.is_symlink():
                raise ValueError('TLS challenge workspace is already in use.')
        if threading.current_thread() is threading.main_thread():
            self.old_sigterm = signal.getsignal(signal.SIGTERM)
            def cancelled(*_):
                raise InterruptedError('TLS challenge request cancelled.')
            signal.signal(signal.SIGTERM, cancelled)
        self.root.mkdir(mode=0o700)
        self.generated.mkdir(mode=0o700)
        names = [self.cfg['primary_domain'], *self.cfg['alternative_names']]
        try:
            try:
                self.servers.append(Server(('0.0.0.0', 443), socket.AF_INET, self.root, names))
                if socket.has_ipv6 and Path('/proc/net/if_inet6').exists():
                    self.servers.append(Server(('::', 443), socket.AF_INET6, self.root, names))
            except OSError:
                raise ValueError('TCP 443 is unavailable. The conflicting service was not stopped; use DNS-01 or HTTP-01 instead.') from None
            self.firewall.open()
            for server in self.servers:
                thread = threading.Thread(target=server.serve_forever, kwargs={'poll_interval': .1}, daemon=True)
                thread.start()
                self.threads.append(thread)
            return self
        except BaseException:
            self.__exit__(None, None, None)
            raise

    def __exit__(self, *_):
        if self.old_sigterm is not None:
            signal.signal(signal.SIGTERM, self.old_sigterm)
            self.old_sigterm = None
        for index, server in enumerate(self.servers):
            if index < len(self.threads):
                server.shutdown()
            server.close_connections()
            server.server_close()
        for thread in self.threads:
            thread.join(timeout=4)
        self.servers.clear()
        self.threads.clear()
        try:
            self.firewall.close()
        finally:
            shutil.rmtree(self.root, ignore_errors=True)
            shutil.rmtree(self.generated, ignore_errors=True)
        return False
