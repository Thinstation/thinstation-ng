"""Temporary, order-scoped RFC 8737 TLS-ALPN-01 responder.

Routing checks precede the OpenSSL handshake; no HTTP or management API is
served. Challenge certificates are generated by dehydrated, never supplied
by the settings API. The listener and expiring firewall access are job-owned.
"""
from contextlib import AbstractContextManager
import hashlib
import json
